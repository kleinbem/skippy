#!/usr/bin/env python3
"""Generate deterministic llama.cpp model-family graph-semantics patches."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from lib.ci_process import cancel_on_signal, command
from lib.rewriter_report import load

# Keep the historical provenance header stable: relocation must not rewrite
# the native patch queue. The tool now lives at skippy/scripts/tools/skippy-stage-rewriter.
PATCH_HEADER = """From 0000000000000000000000000000000000000000 Mon Sep 17 00:00:00 2001
From: Mesh-LLM CI <ci@mesh-llm.local>
Date: Thu, 1 Jan 1970 00:00:00 +0000
Subject: [PATCH] {subject}

Generated by tools/skippy-stage-rewriter from compiler-proven builder
shapes. Auxiliary sidecars and whole-model multi-domain graphs are proven
separately and remain outside the primary decoder stage interval.

---
"""

GENERATOR_VERSION = "0.5.0"
DIFF_HEADER = re.compile(r"^diff --git a/(src/models/[^ ]+) b/[^\n]+$", re.MULTILINE)


def run(args, argv, *, cwd, capture=False, rewriter=False):
    if len(argv) > 16384 or sum(len(os.fsencode(arg)) for arg in argv) > 4 * 1024 * 1024:
        raise ValueError("generator argv exceeds safety limit")
    environment = {key: os.environ[key] for key in (
        "PATH", "HOME", "USERPROFILE", "SYSTEMROOT", "WINDIR", "TMPDIR", "TEMP", "TMP",
        "LANG", "LC_ALL",
    ) if key in os.environ}
    return command(argv, cwd=cwd, capture_stdout=capture, clean_env=False, overrides=environment,
                   timeout=args.timeout or (600 if rewriter else 60), limit=args.max_diff_bytes)


def git(args, root, *argv):
    return run(args, [str(args.git), *argv], cwd=root, capture=True)


def invoke_rewriter(args, source_root, build_dir, rewriter, report, llama_commit, apply):
    sources = sorted((source_root / "src/models").glob("*.cpp"))
    if not sources:
        raise RuntimeError(f"no model sources found under {source_root}")
    argv = [str(rewriter), "--source-root", str(source_root), "--llama-commit", llama_commit,
            "--report", str(report), "-p", str(build_dir)]
    if apply:
        argv.append("--apply")
    for argument in args.extra_arg:
        argv.extend(("--extra-arg", argument))
    argv.extend(str(source) for source in sources)
    run(args, argv, cwd=source_root, rewriter=True)


def patch_text(subject: str, diff: str) -> str:
    return PATCH_HEADER.format(subject=subject) + diff + "-- \n2.54.0\n\n"


def write_utf8(path: Path, content: str) -> None:
    path.write_bytes(content.encode("utf-8", errors="strict"))


def load_family_map(path: Path) -> dict[str, list[str]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if payload.get("schema_version") != 1 or not isinstance(payload.get("families"), dict):
        raise RuntimeError("family source map must use schema_version 1 with a families object")
    result: dict[str, list[str]] = {}
    for family, sources in sorted(payload["families"].items()):
        if not re.fullmatch(r"[a-z0-9][a-z0-9._-]*", family) or not isinstance(sources, list) or not sources:
            raise RuntimeError(f"invalid family source mapping: {family}")
        normalized = sorted(set(sources))
        if len(normalized) != len(sources) or any(
            not re.fullmatch(r"src/models/[a-zA-Z0-9._-]+\.cpp", source)
            for source in normalized
        ):
            raise RuntimeError(f"invalid or duplicate model source mapping: {family}")
        result[family] = normalized
    return result


def split_model_diff(diff: str) -> dict[str, str]:
    matches = list(DIFF_HEADER.finditer(diff))
    if not matches or matches[0].start() != 0:
        raise RuntimeError("generated model diff has an unexpected format")
    sections: dict[str, str] = {}
    for index, match in enumerate(matches):
        source = match.group(1)
        end = matches[index + 1].start() if index + 1 < len(matches) else len(diff)
        if source in sections:
            raise RuntimeError(f"generated model diff repeats source: {source}")
        sections[source] = diff[match.start():end]
    return sections


def load_fixture_families(path: Path) -> set[str]:
    """Require source mappings for causal split targets, not full-model-only workloads."""
    payload = json.loads(path.read_text(encoding="utf-8"))
    models = payload.get("models")
    if not isinstance(models, list):
        raise RuntimeError("family manifest must contain a models array")
    families = {model.get("family") for model in models if isinstance(model, dict)}
    if None in families or len(families) != len(models):
        raise RuntimeError("family manifest contains missing or duplicate family names")
    split_families: set[str] = set()
    for model in models:
        model_class = model.get("class")
        profile = model.get("profile")
        if model_class == "causal_generation":
            if profile not in ("full", "package-oracle", "graph-only"):
                raise RuntimeError("causal fixture requires a split qualification profile")
            split_families.add(model["family"])
        elif model_class in (
            "embedding", "rerank", "encoder_decoder", "ocr",
            "speech_synthesis", "speech_recognition",
        ):
            if profile not in ("workload-smoke", "workload-oracle"):
                raise RuntimeError("non-chat family requires a workload profile")
        else:
            raise RuntimeError("family manifest contains a missing or unknown workload class")
    return split_families


def write_family_shards(
    diff: str,
    output_dir: Path,
    family_map_path: Path,
    family_manifest_path: Path,
) -> dict:
    family_map = load_family_map(family_map_path)
    fixture_families = load_fixture_families(family_manifest_path)
    missing = sorted(fixture_families - set(family_map))
    if missing:
        raise RuntimeError(
            f"family source map does not cover the fixture manifest; missing={missing}"
        )
    reverse: dict[str, set[str]] = {}
    for family, sources in family_map.items():
        for source in sources:
            reverse.setdefault(source, set()).add(family)

    grouped: dict[tuple[str, ...], dict[str, str]] = {}
    for source, section in split_model_diff(diff).items():
        owners = tuple(sorted(reverse.get(source, set())))
        grouped.setdefault(owners, {})[source] = section

    parent = output_dir.parent
    parent.mkdir(parents=True, exist_ok=True)
    temp = Path(tempfile.mkdtemp(prefix=f".{output_dir.name}-", dir=parent))
    shards: list[dict] = []
    try:
        ordered = sorted(grouped.items(), key=lambda item: (not bool(item[0]), item[0]))
        for index, (families, sections) in enumerate(ordered, 1):
            label = "--".join(families) if families else "unmapped"
            filename = f"{index:04d}-family-{label}.patch"
            shard_diff = "".join(sections[source] for source in sorted(sections))
            content = patch_text(f"skippy: annotate {label} graph semantics", shard_diff)
            write_utf8(temp / filename, content)
            shards.append({
                "file": filename,
                "families": list(families),
                "sources": sorted(sections),
                "sha256": hashlib.sha256(content.encode()).hexdigest(),
            })
        series = {
            "schema_version": 1,
            "generator_version": GENERATOR_VERSION,
            "full_patch_sha256": hashlib.sha256(diff.encode()).hexdigest(),
            "shards": shards,
        }
        write_utf8(
            temp / "series.json", json.dumps(series, indent=2, sort_keys=True) + "\n"
        )
        write_utf8(temp / "series", "".join(f"{shard['file']}\n" for shard in shards))
        if output_dir.exists():
            shutil.rmtree(output_dir)
        temp.rename(output_dir)
        return series
    except Exception:
        shutil.rmtree(temp, ignore_errors=True)
        raise


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--build-dir", type=Path)
    parser.add_argument("--git", type=Path, required=True)
    parser.add_argument("--max-diff-bytes", type=int, required=True)
    parser.add_argument("--timeout", type=int)
    parser.add_argument("--rewriter", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--shard-output-dir", type=Path)
    parser.add_argument("--family-source-map", type=Path)
    parser.add_argument("--family-manifest", type=Path)
    parser.add_argument("--report", type=Path)
    parser.add_argument(
        "--diff-base",
        default="HEAD",
        help=(
            "git revision used as the generated patch base; it must contain "
            "all static model semantics and no generated stage controls"
        ),
    )
    parser.add_argument(
        "--extra-arg",
        action="append",
        default=[],
        help="extra compiler argument forwarded to ClangTool (repeatable)",
    )
    argv = list(sys.argv[1:] if argv is None else argv)
    generate = argv[:1] == ["generate"]
    if generate:
        argv = argv[1:]
    # Extra compiler arguments can begin with a dash.
    for index in range(len(argv) - 2, -1, -1):
        if argv[index] == "--extra-arg":
            argv[index:index + 2] = ["--extra-arg=" + argv[index + 1]]
    args = parser.parse_args(argv)
    if not args.git.is_absolute() or (generate and (not args.rewriter or not args.rewriter.is_absolute())):
        parser.error("--git and --rewriter must be absolute")
    if not args.diff_base or args.diff_base.startswith("-"):
        parser.error("--diff-base must be a revision")
    if args.max_diff_bytes <= 0 or (args.timeout is not None and not 1 <= args.timeout <= 86400):
        parser.error("invalid capture limit or timeout")
    if generate and (not args.build_dir or not args.report):
        parser.error("generation requires --build-dir and --report")
    shard_options = (args.shard_output_dir, args.family_source_map, args.family_manifest)
    if sum(value is not None for value in shard_options) not in (0, 3):
        parser.error("shard options must be used together")

    try:
        with cancel_on_signal():
            return generate_patch(args, generate)
    except (OSError, RuntimeError, ValueError, TypeError, KeyError,
            subprocess.SubprocessError, KeyboardInterrupt) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


def generate_patch(args, generate):
    source_root = args.source_root.resolve(strict=True)
    output = args.output.resolve()
    if generate:
        if git(args, source_root, "status", "--porcelain", "--untracked-files=no").strip():
            raise ValueError("source tree must be clean before generation")
        marker = source_root / ".skippy-upstream-sha"
        llama_commit = (marker.read_text(encoding="utf-8").strip() if marker.exists()
                        else git(args, source_root, "rev-parse", "HEAD").strip())
        first_report = args.report.resolve()
        second_report = first_report.with_name(first_report.stem + "-second.json")
        first_report.parent.mkdir(parents=True, exist_ok=True)
        build, rewriter = args.build_dir.resolve(), args.rewriter.resolve()
        invoke_rewriter(args, source_root, build, rewriter, first_report, llama_commit, True)
        first = load(first_report)
        invoke_rewriter(args, source_root, build, rewriter, second_report, llama_commit, False)
        second = load(second_report, idempotence=True)

    diff = git(args, source_root, "diff", "--no-ext-diff", "--binary", "--full-index",
               args.diff_base, "--", "src/models")
    if not diff:
        raise ValueError("generation produced an empty model patch")
    output.parent.mkdir(parents=True, exist_ok=True)
    write_utf8(output, patch_text("skippy: generate model-family stage controls", diff))
    series = (write_family_shards(diff, args.shard_output_dir.resolve(),
                                  args.family_source_map.resolve(), args.family_manifest.resolve())
              if args.shard_output_dir else None)
    if generate:
        print(json.dumps({"output": str(output), "first_summary": first, "second_summary": second,
                          "shards": len(series["shards"]) if series else 0}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
